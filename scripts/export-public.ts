import fs from 'node:fs';
import path from 'node:path';
import net from 'node:net';
import { execFileSync } from 'node:child_process';
import { root } from './runtime.ts';
execFileSync(process.execPath, ['--import', 'tsx', path.join(root, 'scripts/check-secrets.ts')], { cwd: root, stdio: 'inherit' });
const args = process.argv.slice(2).filter(arg => arg !== '--');
const dest = path.resolve(args[0] ?? path.join(root, '.open-source/videos-worth-keeping'));
if (dest === root || root.startsWith(dest + path.sep)) throw new Error('Export destination must not contain the source repository');
const files = execFileSync('git', ['ls-files', '-z'], {cwd: root}).toString().split('\0').filter(Boolean);
const publicRoots = new Set(['.gitignore', '.github', 'LICENSE', 'README.md', 'package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', 'tsconfig.base.json', 'packages', 'scripts']);
const publicDocs = new Set(['docs/configuration.md', 'docs/development.md', 'docs/releasing.md', 'docs/releases/v0.1.0.md']);
const entries: [string, Buffer][] = [];
for (const file of files) {
  if (!publicRoots.has(file.split('/')[0]) && !publicDocs.has(file)) continue;
  if (/(^|\/)(\.git|\.data|\.cache|node_modules|logs|\.pids)(\/|$)/.test(file) || (/(^|\/)\.env[^/]*$/.test(file) && !file.endsWith('/.env.example')) || /\.(?:sqlite|db)(?:-.*)?$/.test(file)) throw new Error(`Private runtime file tracked: ${file}`);
  const blob = execFileSync('git', ['show', ':' + file], {cwd: root});
  const s = blob.toString('utf8');
  if (/\/Users\/[a-zA-Z0-9_-]+\//.test(s) || /[\w.+-]+@[\w.-]+\.[a-zA-Z]{2,}/.test(s)) throw new Error(`Personal path or email in ${file}`);
  for (const m of s.matchAll(/(?<![\w./])(?:\d{1,3}\.){3}\d{1,3}(?![\w.])/g)) {
    if (net.isIPv4(m[0]) && !['127.0.0.1', '0.0.0.0'].includes(m[0])) throw new Error(`Non-local IP in ${file}`);
  }
  entries.push([file, blob]);
}
const marker = path.join(dest, '.public-export');
if (fs.existsSync(dest)) {
  if (!fs.existsSync(marker) || fs.readFileSync(marker,'utf8') !== 'Generated by Videos Worth Keeping public export\n') throw new Error('Destination exists; choose an empty destination');
  // Never overwrite a repository initialized by the user after exporting.
  if (fs.existsSync(path.join(dest,'.git'))) throw new Error('Destination is now a Git repository; choose another destination');
  fs.rmSync(dest, {recursive:true});
}
fs.mkdirSync(dest,{recursive:true});
for (const [file, blob] of entries) {
  const target = path.join(dest,file); fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,blob);
  const mode = execFileSync('git',['ls-files','-s','--',file],{cwd:root,encoding:'utf8'}).slice(0,6);
  if(mode==='100755')fs.chmodSync(target,0o755);
}
fs.writeFileSync(marker,'Generated by Videos Worth Keeping public export\n');
console.log(`Exported ${entries.length} files without Git history: ${dest}`);
