async function call(method: string, route: string, body?: unknown): Promise<[number, Data]> {
  const response = await fetch(base + route, { method, headers: {
    Authorization: `Bearer ${process.env.SMOKE_TOKEN ?? ''}`,
    ...(body === undefined ? {} : { 'Content-Type': 'application/json' }),
  }, body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(90_000) });
  const envelope = await response.json() as { data?: Data };
  diagnostic = `${method} ${route}: HTTP ${response.status} ${JSON.stringify(envelope)}`;
  return [response.status, envelope.data ?? {}];
}
